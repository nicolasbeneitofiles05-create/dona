const {readFileSync}=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const html=readFileSync('index.html','utf8');
const code=html.slice(html.indexOf('const reviewedNotices='),html.indexOf('function renderNotices()'));
const context=vm.createContext({URL});
vm.runInContext(code+';globalThis.sample=reviewedNotices[0];globalThis.state=noticeState;',context);
const sample=context.sample, state=context.state;
const checked=Date.parse(sample.checked_at), expiry=Date.parse(sample.expires_at);
assert.equal(state(sample,checked),'active');
assert.equal(state(sample,expiry-1),'active');
assert.equal(state(sample,expiry),'expired');
assert.equal(state(sample,expiry+86400000),'expired');
assert.equal(state({...sample,expires_at:undefined},checked),'withdrawn');
assert.equal(state({...sample,expires_at:'basura'},checked),'withdrawn');
assert.equal(state({...sample,checked_at:'basura'},checked),'withdrawn');
assert.equal(state({...sample,published_at:'2026-99-99'},checked),'withdrawn');
assert.equal(state({...sample,published_at:'2026-02-30'},checked),'withdrawn');
assert.equal(state({...sample,expires_at:'2027-02-30T12:00:00Z'},checked),'withdrawn');
assert.equal(state({...sample,review_status:'pending',verified:true},checked),'withdrawn');
assert.equal(state({...sample,source_url:'https://www.comunidad.madrid.evil.test/'},checked),'withdrawn');
assert.equal(state({...sample,source_url:'javascript:alert(1)'},checked),'withdrawn');
assert.equal(state({...sample,review_basis:''},checked),'withdrawn');
assert.equal(state(sample,checked-1),'withdrawn');
assert.equal(sample.expires_at,context.sample.expires_at);
assert(!html.includes("fetch("),'No hay feeds o inventarios remotos sin revisión');
assert(!html.includes('Llamamiento Urda'));
assert(!html.includes('Hospital General de Valdepeñas'));
console.log('Avisos: comprobaciones correctas (fechas imposibles, caducidad, fuentes y aviso falso).');
